//! 信息面板在真库上:表和视图的属性能读出来、建表语句是对的。
//! MySQL / MariaDB / PostgreSQL 需要 BASALT_IT 选中目标(见 common);SQLite 总是跑。

mod common;

use basalt_core::session::SessionManager;
use basalt_core::table::TableRef;
use basalt_core::table_info::{PropertyValue, TableDetails};
use common::*;

const CONNECTION: &str = "c1";

const MYSQL_FIXTURE: &str = "
    CREATE DATABASE IF NOT EXISTS basalt_info CHARACTER SET utf8mb4;
    DROP VIEW IF EXISTS basalt_info.people_view;
    DROP TABLE IF EXISTS basalt_info.people;
    CREATE TABLE basalt_info.people (
      id INT AUTO_INCREMENT PRIMARY KEY,
      name VARCHAR(20) NOT NULL
    ) ENGINE=InnoDB COMMENT='人员';
    INSERT INTO basalt_info.people (name) VALUES ('张三'), ('李四');
    CREATE VIEW basalt_info.people_view AS SELECT name FROM basalt_info.people;
";

const PG_FIXTURE: &str = "
    DROP VIEW IF EXISTS public.info_people_view;
    DROP TABLE IF EXISTS public.info_people;
    CREATE TABLE public.info_people (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name varchar(20) NOT NULL
    );
    COMMENT ON TABLE public.info_people IS '人员';
    CREATE INDEX info_people_name ON public.info_people (name);
    INSERT INTO public.info_people (name) VALUES ('张三'), ('李四');
    CREATE VIEW public.info_people_view AS SELECT name FROM public.info_people;
";

const SQLITE_FIXTURE: &str = "
    CREATE TABLE people (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL) STRICT;
    CREATE INDEX people_name ON people (name);
    INSERT INTO people (name) VALUES ('张三'), ('李四');
    CREATE VIEW people_view AS SELECT name FROM people;
";

fn value<'a>(details: &'a TableDetails, label: &str) -> Option<&'a PropertyValue> {
    details
        .properties
        .iter()
        .find(|p| p.label == label)
        .unwrap_or_else(|| panic!("没有「{label}」：{:#?}", details.properties))
        .value
        .as_ref()
}

fn text(details: &TableDetails, label: &str) -> String {
    match value(details, label) {
        Some(PropertyValue::Text(text)) => text.clone(),
        other => panic!("「{label}」不是文本：{other:?}"),
    }
}

async fn details(sessions: &SessionManager, table: &TableRef) -> TableDetails {
    sessions
        .get(CONNECTION)
        .await
        .unwrap()
        .table_details(table)
        .await
        .unwrap()
}

#[tokio::test]
async fn mysql_family_describes_tables_and_views() {
    for target in MYSQL_FAMILY.into_iter().filter(|t| selected(*t)) {
        let pool = sqlx::MySqlPool::connect(&mysql_url(target)).await.unwrap();
        sqlx::raw_sql(MYSQL_FIXTURE).execute(&pool).await.unwrap();
        pool.close().await;
        let sessions = SessionManager::default();
        sessions
            .open(CONNECTION, &params(target, TEST_PASSWORD, None))
            .await
            .unwrap();
        let table = |name: &str| TableRef {
            database: "basalt_info".into(),
            schema: None,
            table: name.into(),
        };
        let people = details(&sessions, &table("people")).await;
        assert_eq!(text(&people, "引擎"), "InnoDB", "{}", target.name);
        assert_eq!(text(&people, "注释"), "人员");
        assert!(matches!(value(&people, "数据长度"), Some(PropertyValue::Bytes(n)) if *n > 0));
        assert!(matches!(
            value(&people, "创建日期"),
            Some(PropertyValue::DateTime(_))
        ));
        assert!(
            people.ddl.starts_with("CREATE TABLE `people`"),
            "{}",
            people.ddl
        );
        assert!(people.ddl.contains("COMMENT='人员'") && people.ddl.ends_with(';'));
        assert!(!people.ddl_generated);

        let view = details(&sessions, &table("people_view")).await;
        assert_eq!(text(&view, "类型"), "视图");
        assert_eq!(text(&view, "可更新"), "是");
        assert!(
            view.ddl.contains("VIEW `basalt_info`.`people_view` AS"),
            "{}",
            view.ddl
        );

        let missing = sessions
            .get(CONNECTION)
            .await
            .unwrap()
            .table_details(&table("nope"))
            .await
            .unwrap_err();
        assert!(
            missing.to_string().contains("找不到表「nope」"),
            "{}：{missing}",
            target.name
        );
    }
}

#[tokio::test]
async fn postgres_describes_tables_and_views() {
    if !selected(POSTGRES) {
        return;
    }
    let pool = match sqlx::PgPool::connect(&postgres_url(FIXTURE_DB)).await {
        Ok(pool) => pool,
        Err(_) => {
            let admin = sqlx::PgPool::connect(&postgres_url("postgres"))
                .await
                .unwrap();
            sqlx::raw_sql(&format!("CREATE DATABASE {FIXTURE_DB}"))
                .execute(&admin)
                .await
                .unwrap();
            sqlx::PgPool::connect(&postgres_url(FIXTURE_DB))
                .await
                .unwrap()
        }
    };
    sqlx::raw_sql(PG_FIXTURE).execute(&pool).await.unwrap();
    pool.close().await;
    let sessions = SessionManager::default();
    sessions
        .open(
            CONNECTION,
            &params(POSTGRES, TEST_PASSWORD, Some(FIXTURE_DB)),
        )
        .await
        .unwrap();
    let table = |name: &str| TableRef {
        database: FIXTURE_DB.into(),
        schema: Some("public".into()),
        table: name.into(),
    };
    let people = details(&sessions, &table("info_people")).await;
    assert_eq!(text(&people, "类型"), "表");
    assert_eq!(text(&people, "注释"), "人员");
    assert_eq!(text(&people, "持久性"), "普通");
    assert!(matches!(value(&people, "总大小"), Some(PropertyValue::Bytes(n)) if *n > 0));
    assert!(people.ddl_generated);
    assert!(
        people
            .ddl
            .starts_with("CREATE TABLE \"public\".\"info_people\""),
        "{}",
        people.ddl
    );
    assert!(people.ddl.contains("info_people_name") && people.ddl.contains("COMMENT ON TABLE"));

    let view = details(&sessions, &table("info_people_view")).await;
    assert_eq!(text(&view, "类型"), "视图");
    assert!(
        view.ddl
            .starts_with("CREATE VIEW \"public\".\"info_people_view\" AS"),
        "{}",
        view.ddl
    );
    assert!(!view.ddl_generated);
}

#[tokio::test]
async fn sqlite_describes_tables_and_views() {
    let dir = tempfile::tempdir().unwrap();
    let path = sqlite_file(dir.path(), "info.db", SQLITE_FIXTURE).await;
    let sessions = SessionManager::default();
    sessions
        .open(CONNECTION, &sqlite_params(&path))
        .await
        .unwrap();
    let table = |name: &str| TableRef {
        database: "main".into(),
        schema: None,
        table: name.into(),
    };
    let people = details(&sessions, &table("people")).await;
    assert_eq!(value(&people, "行"), Some(&PropertyValue::Count(2)));
    assert_eq!(value(&people, "自动递增"), Some(&PropertyValue::Count(2)));
    assert_eq!(value(&people, "索引"), Some(&PropertyValue::Count(1)));
    assert_eq!(text(&people, "STRICT"), "是");
    assert_eq!(text(&people, "WITHOUT ROWID"), "否");
    assert_eq!(
        people.ddl,
        "CREATE TABLE people (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL) STRICT;\n\n\
         CREATE INDEX people_name ON people (name);"
    );

    let view = details(&sessions, &table("people_view")).await;
    assert_eq!(text(&view, "类型"), "视图");
    assert_eq!(
        view.ddl,
        "CREATE VIEW people_view AS SELECT name FROM people;"
    );
}

#[tokio::test]
async fn sqlite_counts_rows_only_up_to_a_limit() {
    let dir = tempfile::tempdir().unwrap();
    let path = sqlite_file(
        dir.path(),
        "big.db",
        "CREATE TABLE big (n INTEGER);
         WITH RECURSIVE s(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM s WHERE n < 100001)
         INSERT INTO big SELECT n FROM s;",
    )
    .await;
    let sessions = SessionManager::default();
    sessions
        .open(CONNECTION, &sqlite_params(&path))
        .await
        .unwrap();
    let big = details(
        &sessions,
        &TableRef {
            database: "main".into(),
            schema: None,
            table: "big".into(),
        },
    )
    .await;
    assert_eq!(text(&big, "行"), "超过 10 万");
}
