//! 并按 ON DELETE 连带删掉、置空别的表里的行——查得出是哪些外键;改名后对象列表里换成新名字、数据还在;
//! 改成已有的名字报错;库名、schema 是空的一律拒绝,不落到会话的当前库上。
//! MySQL / MariaDB / PostgreSQL 需要 BASALT_IT 选中目标(见 common);SQLite 总是跑。

