#[test]
fn indexes_drop_rename_and_create() {
    let mut original = users();
    let mut unique = index("users_email_key", &["email"]);
    unique.unique = true;
    unique.is_constraint = true;
    original.indexes.push(unique);
    original.indexes.push(index("idx_old", &["email"]));
    let mut target = original.clone();
    target.indexes[0].name = "idx_user_name".into();
    target.indexes.remove(2);
    target.indexes.remove(1);
    let mut gin = new_index("idx_mail_trgm", &["email"]);
    gin.method = Some("gin".into());
    target.indexes.push(gin);

    assert_eq!(
        sqls(&plan_for(P, Some(&original), &target)),
        [
            "ALTER TABLE \"public\".\"users\" DROP CONSTRAINT \"users_email_key\"",
            "DROP INDEX \"public\".\"idx_old\"",
            "ALTER INDEX \"public\".\"idx_name\" RENAME TO \"idx_user_name\"",
            "CREATE INDEX \"idx_mail_trgm\" ON \"public\".\"users\" USING gin (\"email\")",
        ]
    );
}

#[test]
fn foreign_keys_drop_rename_and_add() {
    let mut original = users();
    original.columns.push(col("team_id", "integer"));
    original.foreign_keys = vec![
        fk("fk_team", &["team_id"], "teams", &["id"]),
        fk("fk_old", &["team_id"], "old", &["id"]),
    ];
    let mut target = original.clone();
    target.foreign_keys[0].name = "fk_users_team".into();
    target.foreign_keys.remove(1);
    let mut boss = new_fk("fk_boss", &["id"], "users", &[]);
    boss.ref_schema = Some("hr".into());
    target.foreign_keys.push(boss);

    assert_eq!(
        sqls(&plan_for(P, Some(&original), &target)),
        [
            "ALTER TABLE \"public\".\"users\" DROP CONSTRAINT \"fk_old\"",
            "ALTER TABLE \"public\".\"users\" RENAME CONSTRAINT \"fk_team\" TO \"fk_users_team\"",
            "ALTER TABLE \"public\".\"users\" ADD CONSTRAINT \"fk_boss\" FOREIGN KEY (\"id\") REFERENCES \"hr\".\"users\"",
        ]
    );
}

