#[test]
fn identity_and_not_null_toggle() {
    let original = users();
    let mut target = users();
    target.columns[0].auto_increment = false;
    target.columns[2].nullable = false;
    target.columns[2].default = None;

    assert_eq!(
        sqls(&plan_for(P, Some(&original), &target)),
        [
            "ALTER TABLE \"public\".\"users\" ALTER COLUMN \"id\" DROP IDENTITY",
            "ALTER TABLE \"public\".\"users\" ALTER COLUMN \"email\" SET NOT NULL",
        ]
    );

    let back = plan_for(P, Some(&target), &original);
    assert_eq!(
        sqls(&back),
        [
            "ALTER TABLE \"public\".\"users\" ALTER COLUMN \"id\" ADD GENERATED BY DEFAULT AS IDENTITY",
            "ALTER TABLE \"public\".\"users\" ALTER COLUMN \"email\" DROP NOT NULL",
        ]
    );
}

