// 表操作的纯逻辑:改名后换成哪个标签页、会丢掉的修改、各家的说法与结果。
import { describe, expect, it } from "vitest";
import type { MaintenanceMessage, ReferencingKey, TableRef } from "../../lib/types";
import { objectsTab, tableDataTab, tableDesignTab } from "../../stores/tabs";
import {
  DUMP_NOTES,
  MAINTENANCE,
  clearChoices,
  clearRefusal,
  clearTouches,
  clearedNotice,
  formatDuration,
  levelLabel,
  maintenanceNotice,
  maintenanceTitle,
  referenceNotes,
  renamedTab,
  rowsEstimate,
} from "./tableOpsModel";

const users = { database: "FOLIO", schema: "public", table: "users" };

function key(table: string, onDelete: ReferencingKey["onDelete"]): ReferencingKey {
  return { table: { ...users, table }, name: `fk_${table}`, onDelete };
}

describe("tableOpsModel", () => {
  it("replaces the data and design tabs of a renamed table and leaves the rest", () => {
    const data = tableDataTab("c1", "FOLIO", "public", "users");
    expect(renamedTab(data, "c1", users, "members")).toEqual(tableDataTab("c1", "FOLIO", "public", "members"));
    const design = tableDesignTab("c1", "FOLIO", "public", "users");
    expect(renamedTab(design, "c1", users, "members")).toEqual(tableDesignTab("c1", "FOLIO", "public", "members"));
    expect(renamedTab(objectsTab("c1", "FOLIO", "public"), "c1", users, "members")).toBeNull();
    expect(renamedTab(data, "c2", users, "members")).toBeNull();
  });

  it("explains clearing per database and words the outcome", () => {
    expect(clearChoices("sqlite")[1]).toMatchObject({ mode: "truncate", sql: "DELETE FROM + 计数归零" });
    expect(clearChoices("postgres")[1]!.detail).toMatch(/RESTART IDENTITY/);
    expect(clearChoices("mariadb")[1]!.detail).toMatch(/不能回滚/);
    expect(clearedNotice(users, "delete", { rows: 12345 })).toBe("已清空表「users」，删除了 12,345 行。");
    expect(clearedNotice(users, "truncate", { rows: null })).toBe("已截断表「users」。");
    const refused = "cannot truncate a table referenced in a foreign key constraint";
    const both = [key("orders", "cascade"), key("audit", "restrict")];
    expect(clearRefusal("permission denied", "truncate", "postgres", users, [])).toBe("permission denied");
    expect(clearRefusal(refused, "truncate", "postgres", users, [])).toBe(
      `${refused}\n被别的表的外键引用时不能截断，可以改用「清空」。`,
    );
    expect(clearRefusal(refused, "truncate", "mysql", users, both)).toBe(
      `${refused}\n被别的表的外键引用时不能截断。改用「清空」会按外键连带改动 orders 里的行。`,
    );
    // 清空、SQLite 的截断被挡住:换哪种做法都一样,得先处理引用它的行。
    const failed = "FOREIGN KEY constraint failed";
    expect(clearRefusal(failed, "truncate", "sqlite", users, both)).toBe(
      `${failed}\naudit 里还有引用它的行，外键不让删：先删掉或改掉那些行再试。`,
    );
    expect(clearRefusal(failed, "delete", "mysql", users, [])).toBe(
      `${failed}\n别的表里还有引用它的行，外键不让删：先删掉或改掉那些行再试。`,
    );
    expect(rowsEstimate(18204)).toBe("约 18,204 行，估算");
  });

  it("says which other tables a clear would change or be blocked by", () => {
    const keys = [
      key("orders", "cascade"),
      key("orders", "cascade"),
      key("notes", "setNull"),
      key("flags", "setDefault"),
      key("audit", "noAction"),
      { ...key("ledger", "restrict"), table: { database: "FOLIO", schema: "finance", table: "ledger" } },
    ];
    expect(referenceNotes(users, keys, "delete", "postgres")).toEqual({
      warning:
        "会按外键连带改动别的表：orders 里引用它的行会被删掉；notes 里引用它的列会被置空；flags 里引用它的列会改回默认值。",
      note: "audit、FOLIO.finance.ledger 也引用这张表：那边还有引用它的行时，会删不掉。",
    });
    expect(referenceNotes(users, keys, "truncate", "mysql")).toEqual({
      warning: "被 orders、notes、flags、audit、FOLIO.finance.ledger 的外键引用：截断会被数据库拒绝。",
      note: null,
    });
    // SQLite 的截断也是 DELETE,照样连带。
    expect(referenceNotes(users, keys.slice(0, 1), "truncate", "sqlite").warning).toMatch(/^会按外键连带改动/);
    expect(referenceNotes(users, [], "truncate", "postgres")).toEqual({ warning: null, note: null });
    expect(referenceNotes(users, [], "delete", "mysql")).toEqual({ warning: null, note: null });
  });

  it("offers each database its own maintenance and labels the results", () => {
    expect(MAINTENANCE.postgres.map((c) => c.operation)).toEqual(["vacuum", "analyze", "reindex"]);
    expect(MAINTENANCE.mariadb).toBe(MAINTENANCE.mysql);
    expect(DUMP_NOTES.postgres).toMatch(/GENERATED BY DEFAULT.*serial 序列的起始值、步长/);
    expect(levelLabel("warning")).toBe("警告");
    expect(levelLabel("Error_Unknown")).toBe("Error_Unknown");
    expect(formatDuration(87)).toBe("87 毫秒");
    expect(formatDuration(12_340)).toBe("12.3 秒");
    const outcome = { sql: "VACUUM", messages: [], size: null, elapsedMs: 1 };
    expect(maintenanceNotice(users, "清理", outcome)).toBe("「users」清理完成：数据库没有返回消息。");
    const message = (level: string, text: string, kind: MaintenanceMessage["kind"]): MaintenanceMessage => ({
      level,
      text,
      kind,
    });
    const crashed = {
      ...outcome,
      messages: [
        message("note", "checking", "info"),
        message("error", "marked as crashed", "failure"),
        message("status", "Corrupt", "failure"),
      ],
    };
    expect(maintenanceTitle("检查", crashed)).toBe("检查发现问题");
    expect(maintenanceNotice(users, "检查", crashed)).toBe("「users」检查发现问题：错误 marked as crashed。");
    // MariaDB 收集统计时多给的那一行不是问题。
    const mariadb = {
      ...outcome,
      messages: [
        message("status", "Engine-independent statistics collected", "info"),
        message("status", "OK", "success"),
      ],
    };
    expect(maintenanceTitle("分析", mariadb)).toBe("分析完成");
    expect(maintenanceNotice(users, "分析", mariadb)).toBe("「users」分析完成：状态 OK。");
  });

  it("knows which tables a clear touches", () => {
    const keys = [key("orders", "cascade"), key("notes", "setNull"), key("audit", "restrict")];
    const names = (tables: TableRef[]) => tables.map((t) => t.table);
    expect(names(clearTouches(users, keys, "delete", "mysql"))).toEqual(["users", "orders", "notes"]);
    expect(names(clearTouches(users, keys, "truncate", "sqlite"))).toEqual(["users", "orders", "notes"]);
    expect(names(clearTouches(users, keys, "truncate", "postgres"))).toEqual(["users"]);
  });
});
