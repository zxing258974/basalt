struct Fixture<'a> {
    sessions: &'a SessionManager,
    scope: QueryScope,
    database: String,
    schema: Option<String>,
    /// 带库名(schema)、加了引号的表名。
    quoted: fn(&str) -> String,
    label: &'a str,
}

impl Fixture<'_> {
    fn table(&self, name: &str) -> TableRef {
        TableRef {
            database: self.database.clone(),
            schema: self.schema.clone(),
            table: name.into(),
        }
    }

    async fn session(&self) -> std::sync::Arc<Session> {
        self.sessions.get(CONNECTION).await.unwrap()
    }

    async fn run(&self, sql: &str) -> (OutcomeStatus, Vec<String>) {
        let outcome = self
            .sessions
            .run_query("more", CONNECTION, &self.scope, sql)
            .await
            .unwrap();
        let rows = outcome
            .result_sets
            .into_iter()
            .next()
            .map(|s| s.rows)
            .unwrap_or_default();
        let text = rows
            .iter()
            .map(|row| {
                row.iter()
                    .map(|cell| match cell {
                        CellValue::Int(n) => n.to_string(),
                        CellValue::Text(t) => t.clone(),
                        other => format!("{other:?}"),
                    })
                    .collect::<Vec<_>>()
                    .join(" ")
            })
            .collect();
        (outcome.status, text)
    }

    /// 插一行不带 id 的,返回它拿到的 id。
    async fn next_id(&self) -> String {
        let items = (self.quoted)("more_items");
        let (status, _) = self
            .run(&format!("INSERT INTO {items} (name) VALUES ('new')"))
            .await;
        assert_eq!(status, OutcomeStatus::Ok, "{}", self.label);
        let (_, rows) = self.run(&format!("SELECT max(id) FROM {items}")).await;
        rows[0].clone()
    }

    async fn count(&self, table: &str) -> String {
        let (_, rows) = self
            .run(&format!("SELECT count(*) FROM {}", (self.quoted)(table)))
            .await;
        rows[0].clone()
    }

    async fn names(&self) -> Vec<String> {
        self.session()
            .await
            .list_tables(&self.database, self.schema.as_deref())
            .await
            .unwrap()
            .into_iter()
            .map(|t| t.name)
            .collect()
    }
}

async fn exercise(f: &Fixture<'_>, truncate_reports_rows: bool) {
    let session = f.session().await;
    let label = f.label;
    let items = f.table("more_items");

    let cleared = session
        .clear_table(&items, ClearMode::Delete)
        .await
        .unwrap();
    assert_eq!(cleared.rows, Some(3), "{label}：清空报行数");
    assert_eq!(f.count("more_items").await, "0", "{label}");
    assert_eq!(f.next_id().await, "4", "{label}：清空保留自增计数");

    let truncated = session
        .clear_table(&items, ClearMode::Truncate)
        .await
        .unwrap();
    let expected = truncate_reports_rows.then_some(1);
    assert_eq!(truncated.rows, expected, "{label}：截断的行数");
    assert_eq!(f.count("more_items").await, "0", "{label}");
    assert_eq!(f.next_id().await, "1", "{label}：截断后自增计数从头开始");

    let renamed = session
        .rename_table(&items, " more_items_renamed ")
        .await
        .unwrap();
    assert_eq!(renamed, f.table("more_items_renamed"), "{label}");
    let names = f.names().await;
    assert!(
        names.contains(&"more_items_renamed".to_owned())
            && !names.contains(&"more_items".to_owned()),
        "{label}：{names:?}"
    );
    assert_eq!(
        f.count("more_items_renamed").await,
        "1",
        "{label}：数据跟着走"
    );

    let taken = session
        .rename_table(&renamed, "more_parent")
        .await
        .unwrap_err();
    assert_eq!(taken.code(), "database", "{label}：改成已有的名字 {taken}");
    let same = session
        .rename_table(&renamed, "more_items_renamed")
        .await
        .unwrap_err();
    assert_eq!(same.code(), "invalid_data", "{label}");
    session.rename_table(&renamed, "more_items").await.unwrap();
}

/// 被外键引用的表:截断被拒绝、表里的行还在;清空(子表没有引用它的行)照样可以。
/// 引用 more_parent 的外键:自引用不算,另外三张表按名字排好,规则各不相同。
async fn references_are_listed(f: &Fixture<'_>) {
    let session = f.session().await;
    let keys = session
        .referencing_keys(&f.table("more_parent"))
        .await
        .unwrap();
    let found: Vec<(String, OnDelete)> = keys
        .iter()
        .map(|k| (k.table.table.clone(), k.on_delete))
        .collect();
    assert_eq!(found.len(), 3, "{}：{found:?}", f.label);
    assert_eq!(found[0].0, "more_child", "{}", f.label);
    assert!(
        matches!(found[0].1, OnDelete::Restrict | OnDelete::NoAction),
        "{}：{found:?}",
        f.label
    );
    assert_eq!(
        found[1],
        ("more_child_cascade".into(), OnDelete::Cascade),
        "{}",
        f.label
    );
    assert_eq!(
        found[2],
        ("more_child_null".into(), OnDelete::SetNull),
        "{}",
        f.label
    );
    assert_eq!(keys[1].table.database, f.database, "{}", f.label);
    assert_eq!(keys[1].table.schema, f.schema, "{}", f.label);
    if f.label != "SQLite" {
        assert_eq!(
            keys[1].name.as_deref(),
            Some("more_cascade_fk"),
            "{}",
            f.label
        );
    }
    assert!(
        session
            .referencing_keys(&f.table("more_items"))
            .await
            .unwrap()
            .is_empty()
    );
}

/// 清空被引用的表:按外键连带删掉、置空别的表里的行(这就是确认框要提醒的)。
async fn delete_follows_the_foreign_keys(f: &Fixture<'_>) {
    let session = f.session().await;
    let cleared = session
        .clear_table(&f.table("more_parent"), ClearMode::Delete)
        .await
        .unwrap();
    assert_eq!(cleared.rows, Some(1), "{}", f.label);
    assert_eq!(
        f.count("more_child_cascade").await,
        "0",
        "{}：级联删除",
        f.label
    );
    let (_, rows) = f
        .run(&format!(
            "SELECT count(*) FROM {} WHERE parent_id IS NULL",
            (f.quoted)("more_child_null")
        ))
        .await;
    assert_eq!(rows, ["1"], "{}：置空", f.label);
}

/// 别的会话开着事务读过这张表(比如查询页里 BEGIN; SELECT … 没提交):改名、删表等几秒就报「正被占用」,不一直卡着。
async fn busy_table_times_out(f: &Fixture<'_>) {
    let session = f.session().await;
    let items = f.table("more_items");
    let started = std::time::Instant::now();
    let renamed = tokio::time::timeout(
        std::time::Duration::from_secs(30),
        session.rename_table(&items, "more_items_busy"),
    )
    .await
    .expect("改名没有在等锁超时后返回");
    let dropped = tokio::time::timeout(
        std::time::Duration::from_secs(30),
        session.drop_table(&items),
    )
    .await
    .expect("删表没有在等锁超时后返回");
    for result in [renamed.map(|_| ()), dropped] {
        let error = result.unwrap_err();
        assert!(
            error.to_string().contains("正被别的会话占用"),
            "{}：{error}",
            f.label
        );
    }
    assert!(started.elapsed().as_secs() < 25, "{}", f.label);
    assert_eq!(f.count("more_items").await, "1", "{}：表还在", f.label);
}

/// 库名、schema 是空的:各种操作都拒绝,不会落到会话的当前库上。
async fn blank_qualifiers_are_refused(f: &Fixture<'_>, dialect_is_postgres: bool) {
    let session = f.session().await;
    let mut blank = f.table("more_items");
    if dialect_is_postgres {
        blank.schema = Some(String::new());
    } else {
        blank.database = String::new();
    }
    let expected = if dialect_is_postgres {
        "unsupported"
    } else {
        "invalid_data"
    };
    let errors = [
        session
            .clear_table(&blank, ClearMode::Delete)
            .await
            .unwrap_err(),
        session.rename_table(&blank, "x").await.unwrap_err(),
        session.drop_table(&blank).await.unwrap_err(),
        session
            .maintain_table(
                &blank,
                basalt_core::table_ops::maintenance::Maintenance::Analyze,
            )
            .await
            .unwrap_err(),
    ];
    for error in errors {
        assert_eq!(error.code(), expected, "{}：{error}", f.label);
    }
    assert_eq!(f.count("more_items").await, "1", "{}：表没被动过", f.label);
}

async fn referenced_table(f: &Fixture<'_>) {
    let session = f.session().await;
    let parent = f.table("more_parent");
    let error = session
        .clear_table(&parent, ClearMode::Truncate)
        .await
        .unwrap_err();
    assert_eq!(error.code(), "database", "{}：{error}", f.label);
    assert!(
        error.to_string().to_lowercase().contains("foreign key"),
        "{}：{error}",
        f.label
    );
    assert_eq!(f.count("more_parent").await, "1", "{}", f.label);
    delete_follows_the_foreign_keys(f).await;
}

#[tokio::test]
async fn mysql_family_clears_truncates_and_renames() {
    for target in MYSQL_FAMILY.into_iter().filter(|t| selected(*t)) {
        let pool = sqlx::MySqlPool::connect(&mysql_url(target)).await.unwrap();
        sqlx::raw_sql(MYSQL_FIXTURE).execute(&pool).await.unwrap();
        pool.close().await;
        let sessions = SessionManager::default();
        sessions
            .open(CONNECTION, &params(target, TEST_PASSWORD, None))
            .await
            .unwrap();
        let fixture = Fixture {
            sessions: &sessions,
            scope: QueryScope {
                database: Some("basalt_ops_more".into()),
                schema: None,
            },
            database: "basalt_ops_more".into(),
            schema: None,
            quoted: |t| format!("`basalt_ops_more`.`{t}`"),
            label: target.name,
        };
        exercise(&fixture, false).await;
        references_are_listed(&fixture).await;
        blank_qualifiers_are_refused(&fixture, false).await;
        referenced_table(&fixture).await;
        let mut holder =
            sqlx::MySqlConnection::connect(&format!("{}basalt_ops_more", mysql_url(target)))
                .await
                .unwrap();
        let (hold, release) = (
            sqlx::raw_sql("BEGIN; SELECT * FROM more_items;"),
            sqlx::raw_sql("ROLLBACK"),
        );
        hold.execute(&mut holder).await.unwrap();
        busy_table_times_out(&fixture).await;
        release.execute(&mut holder).await.unwrap();
    }
}

