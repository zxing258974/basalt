#[tokio::test]
async fn sqlite_clears_truncates_and_renames() {
    let dir = tempfile::tempdir().unwrap();
    let path = sqlite_file(dir.path(), "more.db", SQLITE_FIXTURE).await;
    let sessions = SessionManager::default();
    sessions
        .open(CONNECTION, &sqlite_params(&path))
        .await
        .unwrap();
    let fixture = Fixture {
        sessions: &sessions,
        scope: QueryScope::default(),
        database: "main".into(),
        schema: None,
        quoted: |t| format!("\"main\".\"{t}\""),
        label: "SQLite",
    };
    // SQLite 的截断就是 DELETE,报得出行数。
    exercise(&fixture, true).await;
    references_are_listed(&fixture).await;
    blank_qualifiers_are_refused(&fixture, false).await;
    // SQLite 的截断就是 DELETE:被引用也不拒绝,照样连带。
    delete_follows_the_foreign_keys(&fixture).await;
}

/// 库里没有 AUTOINCREMENT 表(也就没有 sqlite_sequence)时截断照样可以。
#[tokio::test]
async fn sqlite_truncates_without_a_sequence_table() {
    let dir = tempfile::tempdir().unwrap();
    let path = sqlite_file(
        dir.path(),
        "plain.db",
        "CREATE TABLE plain (id INTEGER PRIMARY KEY, v TEXT); INSERT INTO plain (v) VALUES ('a'), ('b');",
    )
    .await;
    let sessions = SessionManager::default();
    sessions
        .open(CONNECTION, &sqlite_params(&path))
        .await
        .unwrap();
    let session = sessions.get(CONNECTION).await.unwrap();
    let plain = TableRef {
        database: "main".into(),
        schema: None,
        table: "plain".into(),
    };
    let outcome = session
        .clear_table(&plain, ClearMode::Truncate)
        .await
        .unwrap();
    assert_eq!(outcome.rows, Some(2));
}
