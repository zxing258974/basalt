#[test]
fn swapping_names_goes_through_temporary_names() {
    let mut original = users();
    original.columns[2].data_type = "character varying(50)".into();
    original.columns[2].nullable = false;
    original.columns[2].default = original.columns[1].default.clone();
    original.columns[2].comment = original.columns[1].comment.clone();
    let mut target = original.clone();
    target.columns[1].name = "email".into();
    target.columns[2].name = "name".into();

    assert_eq!(
        sqls(&plan_for(P, Some(&original), &target)),
        [
            "ALTER TABLE \"public\".\"users\" RENAME COLUMN \"name\" TO \"__basalt_tmp_1\"",
            "ALTER TABLE \"public\".\"users\" RENAME COLUMN \"email\" TO \"__basalt_tmp_2\"",
            "ALTER TABLE \"public\".\"users\" RENAME COLUMN \"__basalt_tmp_1\" TO \"email\"",
            "ALTER TABLE \"public\".\"users\" RENAME COLUMN \"__basalt_tmp_2\" TO \"name\"",
        ]
    );
}

