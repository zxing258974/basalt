//! 清空、截断、重命名表在真库上:清空保留自增计数、截断从头开始;被外键引用的表截断失败、清空照样可以;
//! 改名后对象列表里换成新名字、数据还在;改成已有的名字报错。
//! MySQL / MariaDB / PostgreSQL 需要 BASALT_IT 选中目标(见 common);SQLite 总是跑。

mod common;

use basalt_core::query::{OutcomeStatus, QueryScope};
use basalt_core::session::{Session, SessionManager};
use basalt_core::table::TableRef;
use basalt_core::table_ops::ClearMode;
use basalt_core::value::CellValue;
use common::*;

const CONNECTION: &str = "c1";

const MYSQL_FIXTURE: &str = "
    CREATE DATABASE IF NOT EXISTS basalt_ops_more CHARACTER SET utf8mb4;
    DROP TABLE IF EXISTS basalt_ops_more.more_child, basalt_ops_more.more_parent,
      basalt_ops_more.more_items, basalt_ops_more.more_items_renamed;
    CREATE TABLE basalt_ops_more.more_items (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(20)) ENGINE=InnoDB;
    INSERT INTO basalt_ops_more.more_items (name) VALUES ('a'), ('b'), ('c');
    CREATE TABLE basalt_ops_more.more_parent (id INT PRIMARY KEY) ENGINE=InnoDB;
    CREATE TABLE basalt_ops_more.more_child (
      id INT PRIMARY KEY, parent_id INT,
      FOREIGN KEY (parent_id) REFERENCES basalt_ops_more.more_parent (id)
    ) ENGINE=InnoDB;
    INSERT INTO basalt_ops_more.more_parent VALUES (1);
";

const PG_FIXTURE: &str = "
    DROP TABLE IF EXISTS public.more_child, public.more_parent, public.more_items, public.more_items_renamed;
    CREATE TABLE public.more_items (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
    INSERT INTO public.more_items (name) VALUES ('a'), ('b'), ('c');
    CREATE TABLE public.more_parent (id integer PRIMARY KEY);
    CREATE TABLE public.more_child (id integer PRIMARY KEY, parent_id integer REFERENCES public.more_parent (id));
    INSERT INTO public.more_parent VALUES (1);
";

const SQLITE_FIXTURE: &str = "
    CREATE TABLE more_items (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);
    INSERT INTO more_items (name) VALUES ('a'), ('b'), ('c');
    CREATE TABLE more_parent (id INTEGER PRIMARY KEY);
";

struct Fixture<'a> {
    sessions: &'a SessionManager,
    scope: QueryScope,
    database: String,
    schema: Option<String>,
    /// 带库名(schema)、加了引号的表名。
    quoted: fn(&str) -> String,
    label: &'a str,
}

impl Fixture<'_> {
    fn table(&self, name: &str) -> TableRef {
        TableRef {
            database: self.database.clone(),
            schema: self.schema.clone(),
            table: name.into(),
        }
    }

    async fn session(&self) -> std::sync::Arc<Session> {
        self.sessions.get(CONNECTION).await.unwrap()
    }

    async fn run(&self, sql: &str) -> (OutcomeStatus, Vec<String>) {
        let outcome = self
            .sessions
            .run_query("more", CONNECTION, &self.scope, sql)
            .await
            .unwrap();
        let rows = outcome
            .result_sets
            .into_iter()
            .next()
            .map(|s| s.rows)
            .unwrap_or_default();
        let text = rows
            .iter()
            .map(|row| {
                row.iter()
                    .map(|cell| match cell {
                        CellValue::Int(n) => n.to_string(),
                        CellValue::Text(t) => t.clone(),
                        other => format!("{other:?}"),
                    })
                    .collect::<Vec<_>>()
                    .join(" ")
            })
            .collect();
        (outcome.status, text)
    }

    /// 插一行不带 id 的,返回它拿到的 id。
    async fn next_id(&self) -> String {
        let items = (self.quoted)("more_items");
        let (status, _) = self
            .run(&format!("INSERT INTO {items} (name) VALUES ('new')"))
            .await;
        assert_eq!(status, OutcomeStatus::Ok, "{}", self.label);
        let (_, rows) = self.run(&format!("SELECT max(id) FROM {items}")).await;
        rows[0].clone()
    }

    async fn count(&self, table: &str) -> String {
        let (_, rows) = self
            .run(&format!("SELECT count(*) FROM {}", (self.quoted)(table)))
            .await;
        rows[0].clone()
    }

    async fn names(&self) -> Vec<String> {
        self.session()
            .await
            .list_tables(&self.database, self.schema.as_deref())
            .await
            .unwrap()
            .into_iter()
            .map(|t| t.name)
            .collect()
    }
}

async fn exercise(f: &Fixture<'_>, truncate_reports_rows: bool) {
    let session = f.session().await;
    let label = f.label;
    let items = f.table("more_items");

    let cleared = session
        .clear_table(&items, ClearMode::Delete)
        .await
        .unwrap();
    assert_eq!(cleared.rows, Some(3), "{label}：清空报行数");
    assert_eq!(f.count("more_items").await, "0", "{label}");
    assert_eq!(f.next_id().await, "4", "{label}：清空保留自增计数");

    let truncated = session
        .clear_table(&items, ClearMode::Truncate)
        .await
        .unwrap();
    let expected = truncate_reports_rows.then_some(1);
    assert_eq!(truncated.rows, expected, "{label}：截断的行数");
    assert_eq!(f.count("more_items").await, "0", "{label}");
    assert_eq!(f.next_id().await, "1", "{label}：截断后自增计数从头开始");

    let renamed = session
        .rename_table(&items, " more_items_renamed ")
        .await
        .unwrap();
    assert_eq!(renamed, f.table("more_items_renamed"), "{label}");
    let names = f.names().await;
    assert!(
        names.contains(&"more_items_renamed".to_owned())
            && !names.contains(&"more_items".to_owned()),
        "{label}：{names:?}"
    );
    assert_eq!(
        f.count("more_items_renamed").await,
        "1",
        "{label}：数据跟着走"
    );

    let taken = session
        .rename_table(&renamed, "more_parent")
        .await
        .unwrap_err();
    assert_eq!(taken.code(), "database", "{label}：改成已有的名字 {taken}");
    let same = session
        .rename_table(&renamed, "more_items_renamed")
        .await
        .unwrap_err();
    assert_eq!(same.code(), "invalid_data", "{label}");
    session.rename_table(&renamed, "more_items").await.unwrap();
}

/// 被外键引用的表:截断被拒绝、表里的行还在;清空(子表没有引用它的行)照样可以。
async fn referenced_table(f: &Fixture<'_>) {
    let session = f.session().await;
    let parent = f.table("more_parent");
    let error = session
        .clear_table(&parent, ClearMode::Truncate)
        .await
        .unwrap_err();
    assert_eq!(error.code(), "database", "{}：{error}", f.label);
    assert!(
        error.to_string().to_lowercase().contains("foreign key"),
        "{}：{error}",
        f.label
    );
    assert_eq!(f.count("more_parent").await, "1", "{}", f.label);
    let cleared = session
        .clear_table(&parent, ClearMode::Delete)
        .await
        .unwrap();
    assert_eq!(cleared.rows, Some(1), "{}", f.label);
}

#[tokio::test]
async fn mysql_family_clears_truncates_and_renames() {
    for target in MYSQL_FAMILY.into_iter().filter(|t| selected(*t)) {
        let pool = sqlx::MySqlPool::connect(&mysql_url(target)).await.unwrap();
        sqlx::raw_sql(MYSQL_FIXTURE).execute(&pool).await.unwrap();
        pool.close().await;
        let sessions = SessionManager::default();
        sessions
            .open(CONNECTION, &params(target, TEST_PASSWORD, None))
            .await
            .unwrap();
        let fixture = Fixture {
            sessions: &sessions,
            scope: QueryScope {
                database: Some("basalt_ops_more".into()),
                schema: None,
            },
            database: "basalt_ops_more".into(),
            schema: None,
            quoted: |t| format!("`basalt_ops_more`.`{t}`"),
            label: target.name,
        };
        exercise(&fixture, false).await;
        referenced_table(&fixture).await;
    }
}

