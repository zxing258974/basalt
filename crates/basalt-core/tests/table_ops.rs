//! 复制表、删除表在真库上:带数据复制后行一样、自增和标识列接着往下走、唯一索引和生成列都在;
//! 只复制结构是空表;重名报错;删掉后对象列表里没有了。
//! MySQL / MariaDB / PostgreSQL 需要 BASALT_IT 选中目标(见 common);SQLite 总是跑。

mod common;

use basalt_core::query::{OutcomeStatus, QueryScope};
use basalt_core::session::SessionManager;
use basalt_core::table::TableRef;
use basalt_core::value::CellValue;
use common::*;

const CONNECTION: &str = "c1";

const MYSQL_FIXTURE: &str = "
    CREATE DATABASE IF NOT EXISTS basalt_ops CHARACTER SET utf8mb4;
    DROP TABLE IF EXISTS basalt_ops.people, basalt_ops.people_copy1, basalt_ops.people_shape;
    CREATE TABLE basalt_ops.people (
      id INT AUTO_INCREMENT PRIMARY KEY,
      name VARCHAR(20) NOT NULL,
      code VARCHAR(10) UNIQUE,
      label VARCHAR(30) AS (CONCAT('#', name)) VIRTUAL
    ) ENGINE=InnoDB COMMENT='人员';
    INSERT INTO basalt_ops.people (id, name, code) VALUES (1, '张三', 'A'), (5, '李四', 'B');
";

const PG_FIXTURE: &str = "
    DROP TABLE IF EXISTS public.ops_people, public.ops_people_copy1, public.ops_people_shape;
    CREATE TABLE public.ops_people (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name varchar(20) NOT NULL,
      code varchar(10) UNIQUE,
      label text GENERATED ALWAYS AS ('#' || name) STORED
    );
    INSERT INTO public.ops_people (id, name, code) VALUES (1, '张三', 'A'), (5, '李四', 'B');
";

const SQLITE_FIXTURE: &str = "
    CREATE TABLE people (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL COLLATE NOCASE,
      code TEXT,
      label TEXT GENERATED ALWAYS AS ('#' || name) VIRTUAL
    );
    CREATE UNIQUE INDEX people_code ON people (code);
    INSERT INTO people (id, name, code) VALUES (1, '张三', 'A'), (5, '李四', 'B');
";

async fn query(
    sessions: &SessionManager,
    scope: &QueryScope,
    sql: &str,
) -> (OutcomeStatus, Vec<Vec<CellValue>>) {
    let outcome = sessions
        .run_query("ops", CONNECTION, scope, sql)
        .await
        .unwrap();
    let rows = outcome
        .result_sets
        .into_iter()
        .next()
        .map(|s| s.rows)
        .unwrap_or_default();
    (outcome.status, rows)
}

fn text(rows: &[Vec<CellValue>]) -> Vec<String> {
    rows.iter()
        .map(|row| {
            row.iter()
                .map(|cell| match cell {
                    CellValue::Null => "∅".to_owned(),
                    CellValue::Int(n) => n.to_string(),
                    CellValue::Text(t) => t.clone(),
                    other => format!("{other:?}"),
                })
                .collect::<Vec<_>>()
                .join(" ")
        })
        .collect()
}

/// `name(table)` 给出带库名、加了引号的表名。
async fn exercise(
    sessions: &SessionManager,
    source: &TableRef,
    scope: &QueryScope,
    name: impl Fn(&str) -> String,
    label: &str,
) {
    let session = sessions.get(CONNECTION).await.unwrap();
    let copy_name = format!("{}_copy1", source.table);
    let shape_name = format!("{}_shape", source.table);

    let copied = session.copy_table(source, &copy_name, true).await.unwrap();
    assert_eq!(
        (copied.table.table.as_str(), copied.rows),
        (copy_name.as_str(), Some(2)),
        "{label}"
    );
    let select = |table: &str| {
        format!(
            "SELECT id, name, code, label FROM {} ORDER BY id",
            name(table)
        )
    };
    assert_eq!(
        text(&query(sessions, scope, &select(&copy_name)).await.1),
        ["1 张三 A #张三", "5 李四 B #李四"],
        "{label}：数据和生成列"
    );
    // 不写 id 的新行接在已复制的最大值后面;唯一索引也跟过来了。
    let insert = |code: &str| {
        format!(
            "INSERT INTO {} (name, code) VALUES ('王五', '{code}')",
            name(&copy_name)
        )
    };
    assert_eq!(
        query(sessions, scope, &insert("C")).await.0,
        OutcomeStatus::Ok,
        "{label}：自增"
    );
    let (_, rows) = query(
        sessions,
        scope,
        &format!("SELECT max(id) FROM {}", name(&copy_name)),
    )
    .await;
    assert_eq!(text(&rows), ["6"], "{label}：新行的 id");
    assert_eq!(
        query(sessions, scope, &insert("A")).await.0,
        OutcomeStatus::Error,
        "{label}：唯一索引"
    );

    let shape = session
        .copy_table(source, &shape_name, false)
        .await
        .unwrap();
    assert_eq!(shape.rows, None);
    let (_, rows) = query(
        sessions,
        scope,
        &format!("SELECT count(*) FROM {}", name(&shape_name)),
    )
    .await;
    assert_eq!(text(&rows), ["0"], "{label}：只复制结构");

    let error = session
        .copy_table(source, &copy_name, true)
        .await
        .unwrap_err();
    assert_eq!(error.code(), "database", "{label}：重名 {error}");

    session.drop_table(&copied.table).await.unwrap();
    session.drop_table(&shape.table).await.unwrap();
    let names: Vec<String> = session
        .list_tables(&source.database, source.schema.as_deref())
        .await
        .unwrap()
        .into_iter()
        .map(|t| t.name)
        .collect();
    assert!(names.contains(&source.table), "{label}");
    assert!(
        !names.contains(&copy_name) && !names.contains(&shape_name),
        "{label}：{names:?}"
    );
    assert_eq!(
        text(&query(sessions, scope, &select(&source.table)).await.1).len(),
        2,
        "{label}：原表不受影响"
    );
}

#[tokio::test]
async fn mysql_family_copies_and_drops_tables() {
    for target in MYSQL_FAMILY.into_iter().filter(|t| selected(*t)) {
        let pool = sqlx::MySqlPool::connect(&mysql_url(target)).await.unwrap();
        sqlx::raw_sql(MYSQL_FIXTURE).execute(&pool).await.unwrap();
        pool.close().await;
        let sessions = SessionManager::default();
        sessions
            .open(CONNECTION, &params(target, TEST_PASSWORD, None))
            .await
            .unwrap();
        let source = TableRef {
            database: "basalt_ops".into(),
            schema: None,
            table: "people".into(),
        };
        let scope = QueryScope {
            database: Some("basalt_ops".into()),
            schema: None,
        };
        exercise(
            &sessions,
            &source,
            &scope,
            |t| format!("`basalt_ops`.`{t}`"),
            target.name,
        )
        .await;
    }
}

#[tokio::test]
async fn postgres_copies_and_drops_tables() {
    if !selected(POSTGRES) {
        return;
    }
    let pool = sqlx::PgPool::connect(&postgres_url(FIXTURE_DB)).await;
    let pool = match pool {
        Ok(pool) => pool,
        Err(_) => {
            // 测试库由别的集成测试建;单独跑这个文件时自己建。
            let admin = sqlx::PgPool::connect(&postgres_url("postgres"))
                .await
                .unwrap();
            sqlx::raw_sql(&format!("CREATE DATABASE {FIXTURE_DB}"))
                .execute(&admin)
                .await
                .unwrap();
            sqlx::PgPool::connect(&postgres_url(FIXTURE_DB))
                .await
                .unwrap()
        }
    };
    sqlx::raw_sql(PG_FIXTURE).execute(&pool).await.unwrap();
    pool.close().await;
    let sessions = SessionManager::default();
    sessions
        .open(
            CONNECTION,
            &params(POSTGRES, TEST_PASSWORD, Some(FIXTURE_DB)),
        )
        .await
        .unwrap();
    let source = TableRef {
        database: FIXTURE_DB.into(),
        schema: Some("public".into()),
        table: "ops_people".into(),
    };
    let scope = QueryScope {
        database: Some(FIXTURE_DB.into()),
        schema: Some("public".into()),
    };
    exercise(
        &sessions,
        &source,
        &scope,
        |t| format!("\"public\".\"{t}\""),
        "PostgreSQL",
    )
    .await;
}

#[tokio::test]
async fn sqlite_copies_and_drops_tables() {
    let dir = tempfile::tempdir().unwrap();
    let path = sqlite_file(dir.path(), "ops.db", SQLITE_FIXTURE).await;
    let sessions = SessionManager::default();
    sessions
        .open(CONNECTION, &sqlite_params(&path))
        .await
        .unwrap();
    let source = TableRef {
        database: "main".into(),
        schema: None,
        table: "people".into(),
    };
    exercise(
        &sessions,
        &source,
        &QueryScope::default(),
        |t| format!("\"main\".\"{t}\""),
        "SQLite",
    )
    .await;

    // 复制出来的表不和原表共用索引名。
    let (_, rows) = query(
        &sessions,
        &QueryScope::default(),
        "SELECT name FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY name",
    )
    .await;
    assert_eq!(text(&rows), ["people_code"]);
}
