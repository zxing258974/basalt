use super::test_support::*;
use super::*;

const P: Dialect = Dialect::Postgres;

fn users() -> TableDesign {
    let mut name = not_null(col("name", "character varying(50)"));
    name.default = Some("''::character varying".into());
    name.comment = Some("姓名".into());
    TableDesign {
        primary_key: vec![cid("id")],
        primary_key_name: Some("users_pkey".into()),
        indexes: vec![index("idx_name", &["name"])],
        ..design(
            P,
            "users",
            vec![
                ColumnDef {
                    auto_increment: true,
                    ..not_null(col("id", "integer"))
                },
                name,
                col("email", "text"),
            ],
        )
    }
}

#[test]
fn create_table_then_indexes_then_comments() {
    let mut target = users();
    target.columns.push(col("team_id", "integer"));
    let mut total = col("score", "numeric");
    total.generated = Some(Generated {
        expression: "length(name)".into(),
        stored: true,
    });
    target.columns.push(total);
    let mut email = new_index("uk_email", &["email"]);
    email.unique = true;
    let mut tags = new_index("idx_team", &["team_id DESC"]);
    tags.method = Some("btree".into());
    target.indexes = vec![email, tags];
    let mut team = fk("fk_team", &["team_id"], "teams", &["id"]);
    team.on_delete = FkAction::Cascade;
    team.on_update = FkAction::Restrict;
    target.foreign_keys = vec![team];
    target.options.comment = Some("用户".into());

    let plan = plan_for(P, None, &target);

    assert_eq!(plan.mode, ExecMode::Transaction);
    assert_eq!(
        sqls(&plan),
        [
            "CREATE TABLE \"public\".\"users\" (\n  \
             \"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  \
             \"name\" character varying(50) NOT NULL DEFAULT ''::character varying,\n  \
             \"email\" text,\n  \
             \"team_id\" integer,\n  \
             \"score\" numeric GENERATED ALWAYS AS (length(name)) STORED,\n  \
             CONSTRAINT \"users_pkey\" PRIMARY KEY (\"id\"),\n  \
             CONSTRAINT \"fk_team\" FOREIGN KEY (\"team_id\") REFERENCES \"public\".\"teams\" (\"id\") ON DELETE CASCADE ON UPDATE RESTRICT\n\
             )",
            "CREATE UNIQUE INDEX \"uk_email\" ON \"public\".\"users\" (\"email\")",
            "CREATE INDEX \"idx_team\" ON \"public\".\"users\" USING btree (\"team_id\" DESC)",
            "COMMENT ON TABLE \"public\".\"users\" IS '用户'",
            "COMMENT ON COLUMN \"public\".\"users\".\"name\" IS '姓名'",
        ]
    );
}

